// Run against the JSON produced by the native -export-check launch and the actual React importer.
// node tools/web-export-check.js <web-export-check.json> <webapp directory>
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const [file, repo] = process.argv.slice(2);
const p = require(path.join(repo, 'tools/load-page'))(path.join(repo, 'src/engine.js'));
const importer = fs.readFileSync(path.join(repo, 'src/store.js'), 'utf8').match(/export function importData\(text\) \{[\s\S]*?\n\}/)[0].replace('export ', '');
const sessions = new Map([['existing', { id: 'existing', date: 0 }]]);
p.set('sessions', sessions);
const importData = new Function('normalizeEnd', 'getSessions', 'switchTo', importer + '; return importData;')(
  p.normalizeEnd, () => sessions, id => { p.set('currentId', id); p.set('S', sessions.get(id)); });
const text = fs.readFileSync(file, 'utf8');
assert.equal(importData(text), 1);
assert(sessions.has('existing'), 'unrelated web sessions survive import');
const s = p.get('S'), ids = s.players.map(p => p.id), r = s.results[0], request = s.scheduled[0];
assert.equal(s.date, 1700000000000);
assert.equal(s.players[0].readyAt, s.date);
assert.equal(s.players[0].since, s.date);
assert.equal(s.players[0].lock, ids[1]);
assert.equal(s.players[0].credit, 2);
assert.equal(s.players[0].rated, 7);
assert.deepEqual(r.a, ids.slice(0, 2));
assert.deepEqual(r.b, ids.slice(2));
assert.equal(r.end - r.start, 720000);
assert.equal(r.changes[ids[0]], 0.125);
assert.equal(r.label, 'Round Robin');
assert.equal(s.courts[0].match.tm, 0);
assert.deepEqual(s.courts[1].plan.a, r.a);
assert.deepEqual(s.courts[1].manual, [ids[0], null]);
assert.equal(request.id, r.scheduled);
assert.deepEqual(request.a, r.a);
assert.equal(s.scheduledActive,request.id);
assert.equal(request.activatedAt,s.date);
assert.deepEqual(request.returning,[ids[0]]);
assert.deepEqual(request.readyJumpers,[ids[0]]);
assert.equal(request.idleReleased,true);
assert.equal(request.assignedCourt,s.courts[0].id);
assert.equal(request.postponedUntil,s.date+600000);
assert.equal(s.courts[0].match.scheduled, request.id);
assert.deepEqual(r.jumpers,[ids[0]]);
assert.deepEqual(s.courts[0].match.jumpers,[ids[0]]);
assert.equal(p.scheduledPenalties()[ids[0]],2);
assert.equal(p.scheduledDone(request), true);
assert.equal(p.played(ids[0]), 1);
assert.equal(p.scheduledDuration('doubles'), 720000);
assert(s.tournament.matches.every(m => [m.a, m.b].every(slot => Array.isArray(slot) && ['e','s','w','l'].includes(slot[0]) && Number.isInteger(slot[1]))));
assert.equal(p.sidesIfReady(s.tournament, s.tournament.matches[0]).length, 2);
const skill = s.players[0].skill;
p.deleteResult(0);
assert.equal(s.players[0].skill, skill - 0.125, 'imported rating changes remain reversible');
assert.equal(p.scheduledDone(request), false);
assert.equal(importData(text), 1);
assert.equal(sessions.size, 2, 'reimport replaces the same session rather than duplicating it');
console.log('Native export imports correctly: dates, players, ratings, locks, games, courts, scheduled matches and tournament slots.');
